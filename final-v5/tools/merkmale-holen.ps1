# merkmale-holen.ps1 - builds js/data/merkmale.js: position and a few features of every place in js/data/orte.js,
# fetched from OpenStreetMap through the Overpass API. Added 2026-10-13 (final-v3).
#
# Run it in PowerShell from the folder final-v5:
#   powershell -ExecutionPolicy Bypass -File tools\merkmale-holen.ps1
#
# What it does:
# 1. reads the OSM objects of all places from js/data/orte.js ("osm": "node/123" or "way/456"),
# 2. asks the Overpass API for their tags (one request; ways come with their centre point),
# 3. keeps only the position and the tags in $KEEP (vegan, wheelchair, outdoor seating, ...),
# 4. writes js/data/merkmale.js (window.MERKMALE, key = id of the place as in orte.js).
# The website itself never talks to OpenStreetMap: it only reads the file written here.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot             # the folder final-v5
$placesFile = Join-Path $root "js\data\orte.js"
$outFile = Join-Path $root "js\data\merkmale.js"

# OSM tags that are kept (meaning: https://wiki.openstreetmap.org/wiki/Key:<name>)
$KEEP = @("diet:vegan", "diet:vegetarian", "diet:halal", "wheelchair", "outdoor_seating", "internet_access",
          "takeaway", "delivery", "organic", "second_hand", "cuisine", "website")

# Servers that answer Overpass requests; the next one is tried when one is busy.
$SERVERS = @("https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter")

# 1. ids of the places: "n1209279102" belongs to node/1209279102, "w..." to a way
$text = [IO.File]::ReadAllText($placesFile)
$nodes = [regex]::Matches($text, '"osm": "node/(\d+)"') | ForEach-Object { $_.Groups[1].Value }
$ways = [regex]::Matches($text, '"osm": "way/(\d+)"') | ForEach-Object { $_.Groups[1].Value }
Write-Host ("{0} nodes, {1} ways in orte.js" -f $nodes.Count, $ways.Count)

# 2. one Overpass request for all of them
$query = "[out:json][timeout:90];(node(id:" + ($nodes -join ",") + ");way(id:" + ($ways -join ",") + "););out tags center;"
$answer = $null
foreach ($server in $SERVERS) {
    try {
        Write-Host "asking $server ..."
        $answer = Invoke-RestMethod -Uri $server -Method Post -Body @{ data = $query } -UserAgent "Quadrate-Studienprojekt (DHBW Mannheim)" -TimeoutSec 180
        if ($answer.elements) { break }
    } catch {
        Write-Host ("  failed: " + $_.Exception.Message)
    }
}
if (-not $answer -or -not $answer.elements) { throw "No answer from Overpass, please try again later." }

# 3. + 4. one line per place, sorted by id, values as JSON strings
$lines = New-Object System.Collections.Generic.List[string]
foreach ($element in ($answer.elements | Sort-Object type, id)) {
    $id = $element.type.Substring(0, 1) + $element.id          # "n123" / "w456" as in orte.js
    if ($element.type -eq "way") { $lat = $element.center.lat; $lon = $element.center.lon }
    else { $lat = $element.lat; $lon = $element.lon }
    $fields = @('"lage": [' + ([string]::Format([Globalization.CultureInfo]::InvariantCulture, "{0:0.00000}, {1:0.00000}", $lat, $lon)) + ']')
    foreach ($key in $KEEP) {
        $value = $element.tags.$key
        if ($key -eq "website" -and -not $value) { $value = $element.tags."contact:website" }
        if ($value) { $fields += ('"' + $key + '": ' + (ConvertTo-Json ([string]$value) -Compress)) }
    }
    $lines.Add('  "' + $id + '": { ' + ($fields -join ", ") + " }")
}

$head = @"
/*
 * merkmale.js - position and features of the places in js/data/orte.js (window.MERKMALE).
 * Version: [V2] data file, read by js/merkmale.js. Added 2026-10-13 (final-v3).
 * Generated by tools/merkmale-holen.ps1 from OpenStreetMap data - do not edit by hand.
 * Key: id of the place in orte.js. Fields:
 *   lage   [latitude, longitude] (ways: their centre), used to find the places near the visitor
 *   and the OpenStreetMap tags as they are, only if the place has them:
 *   diet:vegan, diet:vegetarian, diet:halal (yes | only | no), wheelchair (yes | limited | no),
 *   outdoor_seating, internet_access (wlan | yes | no), takeaway, delivery, organic, second_hand,
 *   cuisine (e.g. "pizza;italian"), website. js/merkmale.js turns them into German words.
 * Places missing here were deleted in OpenStreetMap after orte.js was made.
 * This file is a Derivative Database of OpenStreetMap data and is made available under the
 *   Open Database License 1.0: https://opendatacommons.org/licenses/odbl/1-0/
 * Data (c) OpenStreetMap contributors, https://www.openstreetmap.org/copyright
 */
"@
$stand = (Get-Date).ToString("yyyy-MM-dd")
$body = $head + "`n" + 'window.MERKMALE_META = { "quelle": "OpenStreetMap", "stand": "' + $stand + '", "lizenz": "ODbL 1.0" };' + "`n" +
        "window.MERKMALE = {`n" + ($lines -join ",`n") + "`n};`n"
[IO.File]::WriteAllText($outFile, $body.Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Host ("{0} places written to {1}" -f $lines.Count, $outFile)
